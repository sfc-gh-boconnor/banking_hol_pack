-- Isolation guard: the executive demo must never touch, depend on or satisfy lab content.
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE BANKING_WH;

-- 1. No DEMO_ objects anywhere in BANKING_HOL (tables, views, procedures, agents, services, policies)
SELECT 'demo tables/views in BANKING_HOL' AS CHECK_NAME, COUNT(*) AS N
FROM BANKING_HOL.INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME LIKE 'DEMO\\_%'
UNION ALL
SELECT 'demo procedures in BANKING_HOL', COUNT(*) FROM BANKING_HOL.INFORMATION_SCHEMA.PROCEDURES WHERE PROCEDURE_NAME LIKE 'DEMO\\_%'
UNION ALL
-- 2. Nothing in BANKING_DEMO is owned by an attendee role
SELECT 'BANKING_DEMO objects not owned by HOL_ADMIN', COUNT(*) FROM BANKING_DEMO.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA <> 'INFORMATION_SCHEMA' AND TABLE_OWNER <> 'HOL_ADMIN'
UNION ALL
-- 3. Lab checks read BANKING_HOL only: no lab object depends on BANKING_DEMO
SELECT 'BANKING_HOL objects referencing BANKING_DEMO', COUNT(*) FROM SNOWFLAKE.ACCOUNT_USAGE.OBJECT_DEPENDENCIES
WHERE REFERENCING_DATABASE = 'BANKING_HOL' AND REFERENCED_DATABASE = 'BANKING_DEMO'
UNION ALL
-- 4. Attendees have no write privileges on BANKING_DEMO
SELECT 'write grants on BANKING_DEMO to attendee roles', COUNT(*) FROM SNOWFLAKE.ACCOUNT_USAGE.GRANTS_TO_ROLES
WHERE GRANTEE_NAME IN ('HOL_PARTICIPANT', 'HOL_RESTRICTED') AND TABLE_CATALOG = 'BANKING_DEMO' AND DELETED_ON IS NULL
  AND PRIVILEGE NOT IN ('USAGE', 'SELECT', 'REFERENCES')
UNION ALL
-- 5. The demo inbox (12f) only ever holds invented addresses
SELECT 'DEMO_INBOX messages with a real-looking address', COUNT(*) FROM BANKING_DEMO.EXEC.DEMO_INBOX
WHERE NOT (FROM_ADDR LIKE '%@bank-demo.example' AND TO_ADDR LIKE '%@bank-demo.example');
