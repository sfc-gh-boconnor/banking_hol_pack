-- ---------- Headline numbers ----------
CREATE OR REPLACE TABLE DEMO_RETAIL_KPIS AS
WITH last12 AS (SELECT * FROM BANKING_DEMO.RAW_DATA.RB_MONTHLY_SNAPSHOT
                WHERE MONTH > DATEADD(month, -12, (SELECT MAX(MONTH) FROM BANKING_DEMO.RAW_DATA.RB_MONTHLY_SNAPSHOT)))
SELECT (SELECT COUNT(*) FROM BANKING_DEMO.RAW_DATA.RB_CUSTOMERS)                                AS CUSTOMERS,
       (SELECT COUNT_IF(NOT CHURNED) FROM BANKING_DEMO.RAW_DATA.RB_CUSTOMERS)                     AS ACTIVE_CUSTOMERS,
       (SELECT ROUND(100 * COUNT_IF(CHURNED) / COUNT(*), 1) FROM BANKING_DEMO.RAW_DATA.RB_CUSTOMERS) AS ATTRITION_PCT,
       (SELECT ROUND(SUM(BALANCE_GBP)) FROM BANKING_DEMO.RAW_DATA.RB_ACCOUNTS WHERE STATUS = 'OPEN') AS BALANCES_GBP,
       (SELECT ROUND(SUM(REVENUE_GBP)) FROM last12)                                               AS REVENUE_12M_GBP,
       (SELECT ROUND(SUM(PROFIT_GBP)) FROM last12)                                                AS PROFIT_12M_GBP,
       (SELECT ROUND(SUM(ABS(AMOUNT_GBP))) FROM BANKING_DEMO.RAW_DATA.RB_TRANSACTIONS WHERE IS_FRAUD)   AS FRAUD_LOSS_GBP,
       (SELECT COUNT(*) FROM BANKING_DEMO.RAW_DATA.RB_FRAUD_CASES)                               AS FRAUD_CASES,
       (SELECT COUNT(*) FROM BANKING_DEMO.RETAIL.BRANCHES)                                       AS BRANCHES;

CREATE OR REPLACE TABLE DEMO_CORPORATE_KPIS AS
SELECT COUNT(*) AS PAYMENTS,
       ROUND(SUM(AMOUNT * COALESCE(FX_RATE, 1))) AS VOLUME_GBP,
       ROUND(100 * COUNT_IF(STATUS = 'COMPLETED') / COUNT(*), 2) AS SUCCESS_PCT,
       ROUND(APPROX_PERCENTILE(PROCESSING_TIME_MS, 0.95)) AS P95_MS,
       (SELECT COUNT(*) FROM BANKING_DEMO.RAW_DATA.CUSTOMERS) AS CLIENTS,
       (SELECT COUNT_IF(STATUS <> 'RESOLVED') FROM BANKING_DEMO.RAW_DATA.OPERATIONAL_ALERTS) AS OPEN_ALERTS,
       (SELECT ROUND(AVG(RATING), 2) FROM BANKING_DEMO.RAW_DATA.CUSTOMER_FEEDBACK) AS AVG_RATING
FROM BANKING_DEMO.RAW_DATA.PAYMENTS;

-- Weekly by scheme (despite the name). COMPLETED is kept so success rates can be volume-weighted.
CREATE OR REPLACE TABLE DEMO_PAYMENTS_DAILY AS
SELECT DATE_TRUNC('week', PAYMENT_DATE)::DATE AS WEEK, PAYMENT_TYPE,
       COUNT(*) AS PAYMENTS, COUNT_IF(STATUS = 'COMPLETED') AS COMPLETED,
       ROUND(SUM(AMOUNT * COALESCE(FX_RATE, 1))) AS VOLUME_GBP,
       ROUND(100 * COUNT_IF(STATUS = 'COMPLETED') / COUNT(*), 2) AS SUCCESS_PCT
FROM BANKING_DEMO.RAW_DATA.PAYMENTS GROUP BY 1, 2;

-- Control chart: weekly payment counts (all schemes, and each scheme) against a mean +/- 3
-- standard deviations of the previous 8 weeks. A breach is either explained by the calendar
-- (month end, quarter end, BACS payroll, Christmas) or flagged as unexplained: the ones to
-- investigate. Whole weeks only.
CREATE OR REPLACE TABLE DEMO_PAYMENTS_CONTROL AS
WITH wk AS (
    SELECT WEEK, PAYMENT_TYPE AS SERIES, PAYMENTS FROM DEMO_PAYMENTS_DAILY
    UNION ALL
    SELECT WEEK, 'ALL', SUM(PAYMENTS) FROM DEMO_PAYMENTS_DAILY GROUP BY 1
),
whole AS (
    SELECT * FROM wk WHERE WEEK > (SELECT MIN(WEEK) FROM wk) AND WEEK < (SELECT MAX(WEEK) FROM wk)
),
lim AS (
    SELECT WEEK, SERIES, PAYMENTS,
           AVG(PAYMENTS)    OVER (PARTITION BY SERIES ORDER BY WEEK ROWS BETWEEN 8 PRECEDING AND 1 PRECEDING) AS MEAN,
           STDDEV(PAYMENTS) OVER (PARTITION BY SERIES ORDER BY WEEK ROWS BETWEEN 8 PRECEDING AND 1 PRECEDING) AS SD,
           COUNT(*)         OVER (PARTITION BY SERIES ORDER BY WEEK ROWS BETWEEN 8 PRECEDING AND 1 PRECEDING) AS N
    FROM whole
),
-- what the calendar explains about each week (Monday-start)
cal AS (
    SELECT DISTINCT WEEK,
           (MONTH(WEEK) = 12 AND DAY(WEEK) >= 20) OR (MONTH(WEEK) = 1 AND DAY(WEEK) <= 2) AS XMAS,
           MONTH(WEEK) <> MONTH(DATEADD('day', 4, WEEK)) OR DAY(LAST_DAY(WEEK)) - DAY(WEEK) <= 4 AS MONTH_END,
           DAY(WEEK) <= 28 AND DAY(DATEADD('day', 4, WEEK)) >= 24 AS PAYROLL
    FROM whole
),
flagged AS (
    SELECT l.*, c.XMAS, c.MONTH_END, c.PAYROLL,
           l.N >= 6 AND l.PAYMENTS > l.MEAN + 3 * l.SD AS HIGH,
           l.N >= 6 AND l.PAYMENTS < l.MEAN - 3 * l.SD AS LOW
    FROM lim l JOIN cal c USING (WEEK)
)
-- a calendar reason only explains a breach in the direction it moves volume: month and quarter
-- ends and payroll (BACS and the total only) push it up, Christmas pulls it down
SELECT WEEK, SERIES, PAYMENTS,
       ROUND(MEAN) AS MEAN, ROUND(MEAN + 3 * SD) AS UCL, ROUND(GREATEST(MEAN - 3 * SD, 0)) AS LCL,
       HIGH OR LOW AS BREACH,
       CASE WHEN HIGH AND MONTH_END AND MONTH(WEEK) IN (3, 6, 9, 12) THEN 'Quarter end'
            WHEN HIGH AND MONTH_END THEN 'Month end'
            WHEN HIGH AND PAYROLL AND SERIES IN ('BACS', 'ALL') THEN 'BACS payroll'
            WHEN LOW AND XMAS THEN 'Christmas'
            WHEN HIGH OR LOW THEN 'Unexplained'
       END AS REASON
FROM flagged;

-- ---------- Where we make money: H3 res-7 hexagons ----------
CREATE OR REPLACE TABLE DEMO_PROFIT_BY_H3 AS
WITH p AS (
    SELECT CUSTOMER_ID, SUM(PROFIT_GBP) AS PROFIT, SUM(REVENUE_GBP) AS REVENUE, SUM(COST_TO_SERVE_GBP) AS COST
    FROM BANKING_DEMO.RAW_DATA.RB_MONTHLY_SNAPSHOT
    WHERE MONTH > DATEADD(month, -12, (SELECT MAX(MONTH) FROM BANKING_DEMO.RAW_DATA.RB_MONTHLY_SNAPSHOT))
    GROUP BY 1)
SELECT H3_LATLNG_TO_CELL_STRING(c.HOME_LAT, c.HOME_LON, 7) AS H3,
       ANY_VALUE(c.CITY) AS CITY,
       COUNT(*) AS CUSTOMERS,
       ROUND(SUM(p.PROFIT)) AS PROFIT_GBP, ROUND(SUM(p.REVENUE)) AS REVENUE_GBP, ROUND(SUM(p.COST)) AS COST_GBP,
       ROUND(SUM(p.PROFIT) / COUNT(*)) AS PROFIT_PER_CUSTOMER_GBP,
       ROUND(AVG(c.IMD_DECILE), 1) AS AVG_IMD_DECILE,
       ROUND(100 * COUNT_IF(c.CHURNED) / COUNT(*), 1) AS ATTRITION_PCT,
       ST_ASGEOJSON(H3_CELL_TO_BOUNDARY(H3_LATLNG_TO_CELL_STRING(c.HOME_LAT, c.HOME_LON, 7)))::VARCHAR AS GEOJSON
FROM BANKING_DEMO.RAW_DATA.RB_CUSTOMERS c JOIN p USING (CUSTOMER_ID)
GROUP BY 1;

CREATE OR REPLACE TABLE DEMO_PROFIT_BY_LA AS
SELECT c.LOCAL_AUTHORITY_CODE, ANY_VALUE(c.CITY) AS CITY, COUNT(*) AS CUSTOMERS,
       ROUND(SUM(s.PROFIT_GBP)) AS PROFIT_GBP, ROUND(SUM(s.PROFIT_GBP) / COUNT(DISTINCT c.CUSTOMER_ID)) AS PROFIT_PER_CUSTOMER_GBP,
       ROUND(AVG(c.IMD_DECILE), 1) AS AVG_IMD_DECILE
FROM BANKING_DEMO.RAW_DATA.RB_CUSTOMERS c
JOIN BANKING_DEMO.RAW_DATA.RB_MONTHLY_SNAPSHOT s ON s.CUSTOMER_ID = c.CUSTOMER_ID
WHERE s.MONTH > DATEADD(month, -12, (SELECT MAX(MONTH) FROM BANKING_DEMO.RAW_DATA.RB_MONTHLY_SNAPSHOT))
GROUP BY 1;

-- ---------- Branch network: catchments, profit, coverage, closure impact ----------
CREATE OR REPLACE TABLE DEMO_BRANCHES AS
SELECT b.BRANCH_ID, b.BRANCH_NAME, b.CITY, b.FORMAT, b.LAT, b.LON, b.ANNUAL_COST_GBP, b.STAFF,
       COUNT(c.CUSTOMER_ID) AS HOME_CUSTOMERS,
       ROUND(SUM(p.PROFIT)) AS CUSTOMER_PROFIT_12M_GBP,
       (SELECT COUNT(*) FROM BANKING_DEMO.RETAIL.BRANCH_VISITS v WHERE v.BRANCH_ID = b.BRANCH_ID) AS VISITS
FROM BANKING_DEMO.RETAIL.BRANCHES b
LEFT JOIN BANKING_DEMO.RAW_DATA.RB_CUSTOMERS c ON c.HOME_BRANCH_ID = b.BRANCH_ID
LEFT JOIN (SELECT CUSTOMER_ID, SUM(PROFIT_GBP) AS PROFIT FROM BANKING_DEMO.RAW_DATA.RB_MONTHLY_SNAPSHOT
           WHERE MONTH > DATEADD(month, -12, (SELECT MAX(MONTH) FROM BANKING_DEMO.RAW_DATA.RB_MONTHLY_SNAPSHOT))
           GROUP BY 1) p ON p.CUSTOMER_ID = c.CUSTOMER_ID
GROUP BY ALL;

CREATE OR REPLACE TABLE DEMO_BRANCH_CATCHMENTS AS
SELECT BRANCH_ID, PROFILE, MINUTES,
       ST_ASGEOJSON(ST_SIMPLIFY(CATCHMENT, 150))::VARCHAR AS GEOJSON
FROM BANKING_DEMO.RETAIL.BRANCH_ISOCHRONES;

-- Drive time from each customer's home (H3 res 8) to their nearest branch, and to the nearest
-- branch if their home branch closed
CREATE OR REPLACE TABLE DEMO_CUSTOMER_ACCESS AS
WITH cust AS (
    SELECT CUSTOMER_ID, HOME_BRANCH_ID, CITY, H3_LATLNG_TO_CELL_STRING(HOME_LAT, HOME_LON, 8) AS H3_8
    FROM BANKING_DEMO.RAW_DATA.RB_CUSTOMERS WHERE NOT CHURNED),
drive AS (SELECT BRANCH_ID, H3_CELL, DURATION_S FROM BANKING_DEMO.RETAIL.BRANCH_CELL_TRAVEL WHERE PROFILE = 'driving-car')
SELECT c.CUSTOMER_ID, c.HOME_BRANCH_ID, c.CITY, c.H3_8,
       MIN(d.DURATION_S) / 60 AS NEAREST_MIN,
       MIN(IFF(d.BRANCH_ID <> c.HOME_BRANCH_ID, d.DURATION_S, NULL)) / 60 AS NEAREST_OTHER_MIN
FROM cust c LEFT JOIN drive d ON d.H3_CELL = c.H3_8
GROUP BY ALL;

CREATE OR REPLACE TABLE DEMO_BRANCH_CLOSURE_IMPACT AS
SELECT a.HOME_BRANCH_ID AS BRANCH_ID,
       COUNT(*) AS HOME_CUSTOMERS,
       -- newly cut off: within 20 minutes of a branch today, over 20 if this one closed
       COUNT_IF(a.NEAREST_MIN <= 20 AND COALESCE(a.NEAREST_OTHER_MIN, 999) > 20) AS CUSTOMERS_OVER_20_MIN,
       ROUND(SUM(IFF(a.NEAREST_MIN <= 20 AND COALESCE(a.NEAREST_OTHER_MIN, 999) > 20, p.PROFIT, 0))) AS PROFIT_AT_RISK_GBP,
       ROUND(AVG(COALESCE(a.NEAREST_OTHER_MIN, 60) - a.NEAREST_MIN), 1) AS AVG_EXTRA_MIN
FROM DEMO_CUSTOMER_ACCESS a
LEFT JOIN (SELECT CUSTOMER_ID, SUM(PROFIT_GBP) AS PROFIT FROM BANKING_DEMO.RAW_DATA.RB_MONTHLY_SNAPSHOT
           WHERE MONTH > DATEADD(month, -12, (SELECT MAX(MONTH) FROM BANKING_DEMO.RAW_DATA.RB_MONTHLY_SNAPSHOT))
           GROUP BY 1) p USING (CUSTOMER_ID)
GROUP BY 1;

-- Business banking customers (07b) who pay cash in at their home branch: same rule as above,
-- newly more than 20 minutes away if it closed. Cash is 12 months of counter deposits.
CREATE OR REPLACE TABLE DEMO_BUSINESS_CLOSURE_IMPACT AS
WITH acc AS (
    SELECT b.BUSINESS_ID, b.BUSINESS_TYPE, b.HOME_BRANCH_ID, b.TREASURER_DIGITAL,
           MIN(d.DURATION_S) / 60 AS NEAREST_MIN,
           MIN(IFF(d.BRANCH_ID <> b.HOME_BRANCH_ID, d.DURATION_S, NULL)) / 60 AS NEAREST_OTHER_MIN
    FROM BANKING_DEMO.RETAIL.BUSINESS_CUSTOMERS b
    LEFT JOIN BANKING_DEMO.RETAIL.BRANCH_CELL_TRAVEL d ON d.H3_CELL = b.HOME_H3_CELL AND d.PROFILE = 'driving-car'
    GROUP BY ALL),
cash AS (SELECT BUSINESS_ID, SUM(CASH_GBP + CHEQUES_GBP) AS PAID_IN, COUNT(*) AS VISITS
         FROM BANKING_DEMO.RETAIL.BUSINESS_CASH_DEPOSITS GROUP BY 1)
SELECT a.HOME_BRANCH_ID AS BRANCH_ID,
       COUNT(*) AS BUSINESSES,
       COUNT_IF(a.BUSINESS_TYPE = 'SMALL_BUSINESS') AS SMALL_BUSINESSES,
       COUNT_IF(a.BUSINESS_TYPE = 'CHARITY') AS CHARITIES,
       COUNT_IF(a.BUSINESS_TYPE = 'CLUB') AS CLUBS,
       COUNT_IF(NOT a.TREASURER_DIGITAL) AS NOT_DIGITAL,
       COUNT_IF(a.NEAREST_MIN <= 20 AND COALESCE(a.NEAREST_OTHER_MIN, 999) > 20) AS BUSINESSES_OVER_20_MIN,
       ROUND(SUM(c.PAID_IN)) AS CASH_PAID_IN_12M_GBP,
       SUM(c.VISITS) AS PAYING_IN_VISITS_12M,
       ROUND(AVG(COALESCE(a.NEAREST_OTHER_MIN, 60) - a.NEAREST_MIN), 1) AS AVG_EXTRA_MIN
FROM acc a LEFT JOIN cash c USING (BUSINESS_ID)
GROUP BY 1;

-- Closure map: customer hexagons at res 7 (city view) and res 8 (zoomed in, the ORS matrix's own
-- resolution), each with the drive time in minutes to every branch in its city, looked up from
-- BRANCH_CELL_TRAVEL. DRIVE is a compact 'BRANCH_ID:minutes,...' string so the map can show,
-- on click, the time to the selected branch and to the next nearest if it closed. A res-7 time is
-- the customer-weighted average of its res-8 children.
CREATE OR REPLACE TABLE DEMO_BRANCH_HEXES AS
WITH p AS (
    SELECT CUSTOMER_ID, SUM(PROFIT_GBP) AS PROFIT FROM BANKING_DEMO.RAW_DATA.RB_MONTHLY_SNAPSHOT
    WHERE MONTH > DATEADD(month, -12, (SELECT MAX(MONTH) FROM BANKING_DEMO.RAW_DATA.RB_MONTHLY_SNAPSHOT))
    GROUP BY 1),
c AS (
    SELECT c.CUSTOMER_ID, c.CITY, COALESCE(p.PROFIT, 0) AS PROFIT,
           H3_LATLNG_TO_CELL_STRING(c.HOME_LAT, c.HOME_LON, 8) AS H3_8,
           H3_LATLNG_TO_CELL_STRING(c.HOME_LAT, c.HOME_LON, 7) AS H3_7
    FROM BANKING_DEMO.RAW_DATA.RB_CUSTOMERS c LEFT JOIN p USING (CUSTOMER_ID) WHERE NOT c.CHURNED),
hex AS (
    SELECT 8 AS RES, H3_8 AS H3, ANY_VALUE(CITY) AS CITY, COUNT(*) AS CUSTOMERS, ROUND(SUM(PROFIT)) AS PROFIT_GBP FROM c GROUP BY 2
    UNION ALL
    SELECT 7, H3_7, ANY_VALUE(CITY), COUNT(*), ROUND(SUM(PROFIT)) FROM c GROUP BY 2),
drive8 AS (
    SELECT t.H3_CELL AS H3_8, t.BRANCH_ID, t.DURATION_S / 60 AS MINS
    FROM BANKING_DEMO.RETAIL.BRANCH_CELL_TRAVEL t
    JOIN BANKING_DEMO.RETAIL.BRANCHES b USING (BRANCH_ID)
    WHERE t.PROFILE = 'driving-car' AND t.H3_CELL IN (SELECT H3_8 FROM c)),
drive AS (
    SELECT 8 AS RES, H3_8 AS H3, BRANCH_ID, MINS FROM drive8
    UNION ALL
    SELECT 7, c8.H3_7, d.BRANCH_ID, SUM(d.MINS * c8.N) / SUM(c8.N)
    FROM drive8 d JOIN (SELECT H3_8, ANY_VALUE(H3_7) AS H3_7, COUNT(*) AS N FROM c GROUP BY 1) c8 USING (H3_8)
    GROUP BY 1, 2, 3)
SELECT h.RES, h.H3, h.CITY, h.CUSTOMERS, h.PROFIT_GBP,
       ST_ASGEOJSON(H3_CELL_TO_BOUNDARY(h.H3))::VARCHAR AS GEOJSON,
       LISTAGG(d.BRANCH_ID || ':' || ROUND(d.MINS, 1), ',') WITHIN GROUP (ORDER BY d.MINS) AS DRIVE
FROM hex h LEFT JOIN drive d ON d.RES = h.RES AND d.H3 = h.H3
GROUP BY ALL;

-- Coverage gaps: res-7 hexes with profitable customers more than 20 minutes from any branch
CREATE OR REPLACE TABLE DEMO_COVERAGE_GAPS AS
SELECT H3_CELL_TO_PARENT(a.H3_8, 7) AS H3, ANY_VALUE(a.CITY) AS CITY, COUNT(*) AS CUSTOMERS,
       ROUND(SUM(p.PROFIT)) AS PROFIT_GBP, ROUND(AVG(COALESCE(a.NEAREST_MIN, 60)), 1) AS AVG_DRIVE_MIN,
       ST_ASGEOJSON(H3_CELL_TO_BOUNDARY(H3_CELL_TO_PARENT(a.H3_8, 7)))::VARCHAR AS GEOJSON
FROM DEMO_CUSTOMER_ACCESS a
JOIN (SELECT CUSTOMER_ID, SUM(PROFIT_GBP) AS PROFIT FROM BANKING_DEMO.RAW_DATA.RB_MONTHLY_SNAPSHOT
      WHERE MONTH > DATEADD(month, -12, (SELECT MAX(MONTH) FROM BANKING_DEMO.RAW_DATA.RB_MONTHLY_SNAPSHOT))
      GROUP BY 1) p USING (CUSTOMER_ID)
WHERE COALESCE(a.NEAREST_MIN, 999) > 20
GROUP BY 1
HAVING COUNT(*) >= 3;

-- ---------- Follow the money: the fraud network ----------
-- The lab's payee names are generic ("New payee", "Safe account"), so the demo adds
-- its own deterministic, synthetic beneficiary layer: mule accounts that receive from
-- several victims, controllers they pay on to, and devices they share. DEMO ONLY.
CREATE OR REPLACE TABLE DEMO_BENEFICIARY_ACCOUNTS
    COMMENT = 'DEMO ONLY, synthetic: mule accounts behind APP scam and account takeover payments' AS
WITH f AS (
    SELECT t.TXN_ID, t.CUSTOMER_ID, t.TXN_TS, ABS(t.AMOUNT_GBP) AS AMOUNT_GBP, t.FRAUD_TYPE, t.MERCHANT
    FROM BANKING_DEMO.RAW_DATA.RB_TRANSACTIONS t
    WHERE t.IS_FRAUD AND t.CHANNEL = 'FPS_OUT')
SELECT f.*,
       -- 36 mule accounts; victims in the same fortnight tend to share one, like a real ring
       'MULE-' || LPAD(MOD(ABS(HASH(f.FRAUD_TYPE, DATE_TRUNC('week', f.TXN_TS), MOD(ABS(HASH(f.CUSTOMER_ID)), 3))), 36)::VARCHAR, 3, '0') AS MULE_ACCOUNT,
       'SORT 20-' || LPAD(MOD(ABS(HASH(f.FRAUD_TYPE)), 90)::VARCHAR, 2, '0') AS RECEIVING_BANK
FROM f;

CREATE OR REPLACE TABLE DEMO_FRAUD_GRAPH_NODES AS
SELECT 'VICTIM' AS NODE_TYPE, c.CUSTOMER_ID AS NODE_ID, c.FIRST_NAME || ' ' || c.LAST_NAME AS LABEL,
       c.CITY AS DETAIL, SUM(b.AMOUNT_GBP) AS AMOUNT_GBP
FROM DEMO_BENEFICIARY_ACCOUNTS b JOIN BANKING_DEMO.RAW_DATA.RB_CUSTOMERS c USING (CUSTOMER_ID) GROUP BY ALL
UNION ALL
SELECT 'MULE', MULE_ACCOUNT, MULE_ACCOUNT, COUNT(DISTINCT CUSTOMER_ID) || ' victims', SUM(AMOUNT_GBP)
FROM DEMO_BENEFICIARY_ACCOUNTS GROUP BY MULE_ACCOUNT
UNION ALL
SELECT 'CONTROLLER', 'CTRL-' || MOD(ABS(HASH(MULE_ACCOUNT)), 6), 'Controller ' || MOD(ABS(HASH(MULE_ACCOUNT)), 6), 'onward transfers', SUM(AMOUNT_GBP) * 0.85
FROM DEMO_BENEFICIARY_ACCOUNTS GROUP BY 2, 3
UNION ALL
SELECT 'DEVICE', 'DEV-' || MOD(ABS(HASH(MULE_ACCOUNT, 'd')), 14), 'Device ' || MOD(ABS(HASH(MULE_ACCOUNT, 'd')), 14), 'shared login device', NULL
FROM DEMO_BENEFICIARY_ACCOUNTS GROUP BY 2, 3
UNION ALL
SELECT 'CASE', f.CASE_ID, f.CASE_ID, f.FRAUD_TYPE || ' · ' || f.DECISION, f.LOSS_GBP
FROM BANKING_DEMO.RAW_DATA.RB_FRAUD_CASES f WHERE f.CUSTOMER_ID IN (SELECT CUSTOMER_ID FROM DEMO_BENEFICIARY_ACCOUNTS)
UNION ALL
SELECT 'SAR', s.SAR_ID, s.SAR_ID, s.PATTERN, NULL
FROM BANKING_DEMO.RAW_DATA.RB_SAR_NARRATIVES s WHERE s.CUSTOMER_ID IN (SELECT CUSTOMER_ID FROM DEMO_BENEFICIARY_ACCOUNTS);

CREATE OR REPLACE TABLE DEMO_FRAUD_GRAPH_EDGES AS
SELECT CUSTOMER_ID AS SOURCE, MULE_ACCOUNT AS TARGET, 'PAID' AS EDGE_TYPE, SUM(AMOUNT_GBP) AS AMOUNT_GBP, COUNT(*) AS TXNS
FROM DEMO_BENEFICIARY_ACCOUNTS GROUP BY 1, 2
UNION ALL
SELECT MULE_ACCOUNT, 'CTRL-' || MOD(ABS(HASH(MULE_ACCOUNT)), 6), 'MOVED_ON', SUM(AMOUNT_GBP) * 0.85, COUNT(*)
FROM DEMO_BENEFICIARY_ACCOUNTS GROUP BY 1, 2
UNION ALL
SELECT DISTINCT MULE_ACCOUNT, 'DEV-' || MOD(ABS(HASH(MULE_ACCOUNT, 'd')), 14), 'SAME_DEVICE', NULL, NULL
FROM DEMO_BENEFICIARY_ACCOUNTS
UNION ALL
SELECT f.CUSTOMER_ID, f.CASE_ID, 'REPORTED', f.LOSS_GBP, 1
FROM BANKING_DEMO.RAW_DATA.RB_FRAUD_CASES f WHERE f.CUSTOMER_ID IN (SELECT CUSTOMER_ID FROM DEMO_BENEFICIARY_ACCOUNTS)
UNION ALL
SELECT s.CUSTOMER_ID, s.SAR_ID, 'SAR_FILED', NULL, 1
FROM BANKING_DEMO.RAW_DATA.RB_SAR_NARRATIVES s WHERE s.CUSTOMER_ID IN (SELECT CUSTOMER_ID FROM DEMO_BENEFICIARY_ACCOUNTS);

SELECT 'DEMO_PROFIT_BY_H3' AS T, COUNT(*) N FROM DEMO_PROFIT_BY_H3
UNION ALL SELECT 'DEMO_BRANCH_CATCHMENTS', COUNT(*) FROM DEMO_BRANCH_CATCHMENTS
UNION ALL SELECT 'DEMO_BRANCH_HEXES', COUNT(*) FROM DEMO_BRANCH_HEXES
UNION ALL SELECT 'DEMO_PAYMENTS_CONTROL', COUNT(*) FROM DEMO_PAYMENTS_CONTROL
UNION ALL SELECT 'DEMO_BRANCH_CLOSURE_IMPACT', COUNT(*) FROM DEMO_BRANCH_CLOSURE_IMPACT
UNION ALL SELECT 'DEMO_COVERAGE_GAPS', COUNT(*) FROM DEMO_COVERAGE_GAPS
UNION ALL SELECT 'DEMO_FRAUD_GRAPH_NODES', COUNT(*) FROM DEMO_FRAUD_GRAPH_NODES
UNION ALL SELECT 'DEMO_FRAUD_GRAPH_EDGES', COUNT(*) FROM DEMO_FRAUD_GRAPH_EDGES;

-- ---------- Live SLA breaches: a dynamic table kept within a minute of the Iceberg payment tables ----------
-- Payment level: a payment breaches when it fails or runs past its scheme's maximum processing time.
-- It only refreshes when the source changes, so it costs nothing while the demo data is static.
CREATE OR REPLACE DYNAMIC TABLE DEMO_DT_SLA_BREACHES
  TARGET_LAG = '1 minute' WAREHOUSE = BANKING_WH
  COMMENT = 'Exec demo: SLA breaches per scheme, kept within a minute of the Iceberg payment tables'
AS
SELECT p.PAYMENT_TYPE, s.SLA_NAME, s.MAX_PROCESSING_TIME_MS, s.TARGET_SUCCESS_RATE,
       COUNT(*) AS PAYMENTS,
       COUNT_IF(p.STATUS = 'FAILED' OR p.PROCESSING_TIME_MS > s.MAX_PROCESSING_TIME_MS) AS BREACHES,
       ROUND(SUM(IFF(p.STATUS = 'FAILED' OR p.PROCESSING_TIME_MS > s.MAX_PROCESSING_TIME_MS, p.AMOUNT * COALESCE(p.FX_RATE, 1), 0))) AS BREACH_VALUE_GBP,
       ROUND(100 * COUNT_IF(p.STATUS = 'COMPLETED') / COUNT(*), 2) AS SUCCESS_PCT,
       MAX(p.PAYMENT_DATE) AS LATEST_PAYMENT
FROM BANKING_DEMO.RAW_DATA.PAYMENTS p
JOIN BANKING_DEMO.RAW_DATA.SLA_DEFINITIONS s ON s.PAYMENT_TYPE = p.PAYMENT_TYPE
GROUP BY 1, 2, 3, 4;
GRANT SELECT ON DYNAMIC TABLE DEMO_DT_SLA_BREACHES TO ROLE HOL_PARTICIPANT;

