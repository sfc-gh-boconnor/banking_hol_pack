-- =====================================================
-- GOV5: Protect personal data at scale (solution / catch-up)
-- One masking policy per data type, attached to the PERSONAL_DATA tag from GOV4, so
-- every tagged column is protected by role: owner sees all, builder sees banded
-- values, everyone else sees nothing. Run as HOL_PARTICIPANT after GOV4.
-- =====================================================
USE ROLE HOL_PARTICIPANT;
USE WAREHOUSE BANKING_WH;
USE SCHEMA BANKING_HOL.GOVERNANCE;

-- 1. One policy per data type, driven by the tag value
CREATE OR REPLACE MASKING POLICY MASK_PD_STRING AS (VAL VARCHAR) RETURNS VARCHAR ->
  CASE
    WHEN CURRENT_ROLE() = 'HOL_ADMIN' THEN VAL
    WHEN CURRENT_ROLE() = 'HOL_PARTICIPANT' THEN
      CASE SYSTEM$GET_TAG_ON_CURRENT_COLUMN('BANKING_HOL.GOVERNANCE.PERSONAL_DATA')
        WHEN 'FINANCIAL_CRIME' THEN '[restricted]'
        WHEN 'IDENTITY' THEN LEFT(VAL, 1) || '****'
        WHEN 'CONTACT'  THEN LEFT(VAL, 3) || '****'
        ELSE VAL
      END
    ELSE '****'
  END;

CREATE OR REPLACE MASKING POLICY MASK_PD_NUMBER AS (VAL NUMBER) RETURNS NUMBER ->
  CASE
    WHEN CURRENT_ROLE() = 'HOL_ADMIN' THEN VAL
    WHEN CURRENT_ROLE() = 'HOL_PARTICIPANT' THEN
      CASE WHEN ABS(VAL) >= 10000 THEN ROUND(VAL, -3) WHEN ABS(VAL) >= 100 THEN ROUND(VAL, -1) ELSE ROUND(VAL, 0) END
    ELSE NULL
  END;

CREATE OR REPLACE MASKING POLICY MASK_PD_DATE AS (VAL DATE) RETURNS DATE ->
  CASE
    WHEN CURRENT_ROLE() = 'HOL_ADMIN' THEN VAL
    WHEN CURRENT_ROLE() = 'HOL_PARTICIPANT' THEN DATE_TRUNC('YEAR', VAL)
    ELSE NULL
  END;

-- 2. Attach them to the tag: every tagged column, now and in future
ALTER TAG PERSONAL_DATA SET MASKING POLICY MASK_PD_STRING;
ALTER TAG PERSONAL_DATA SET MASKING POLICY MASK_PD_NUMBER;
ALTER TAG PERSONAL_DATA SET MASKING POLICY MASK_PD_DATE;

-- 3. Let the restricted role read the tables (it sees masked values only)
GRANT SELECT ON ALL TABLES IN SCHEMA BANKING_HOL.GOVERNANCE TO ROLE HOL_RESTRICTED;

-- 4. Prove the coverage: every tagged column and the policy that protects it
CREATE OR REPLACE VIEW MASKING_COVERAGE AS
WITH TAGGED AS (
  SELECT OBJECT_NAME AS TABLE_NAME, COLUMN_NAME, TAG_VALUE FROM TABLE(BANKING_HOL.INFORMATION_SCHEMA.TAG_REFERENCES_ALL_COLUMNS('BANKING_HOL.GOVERNANCE.RB_CUSTOMERS', 'table')) WHERE TAG_NAME = 'PERSONAL_DATA'
  UNION ALL SELECT OBJECT_NAME, COLUMN_NAME, TAG_VALUE FROM TABLE(BANKING_HOL.INFORMATION_SCHEMA.TAG_REFERENCES_ALL_COLUMNS('BANKING_HOL.GOVERNANCE.RB_ACCOUNTS', 'table')) WHERE TAG_NAME = 'PERSONAL_DATA'
  UNION ALL SELECT OBJECT_NAME, COLUMN_NAME, TAG_VALUE FROM TABLE(BANKING_HOL.INFORMATION_SCHEMA.TAG_REFERENCES_ALL_COLUMNS('BANKING_HOL.GOVERNANCE.RB_TRANSACTIONS', 'table')) WHERE TAG_NAME = 'PERSONAL_DATA'
  UNION ALL SELECT OBJECT_NAME, COLUMN_NAME, TAG_VALUE FROM TABLE(BANKING_HOL.INFORMATION_SCHEMA.TAG_REFERENCES_ALL_COLUMNS('BANKING_HOL.GOVERNANCE.RB_CALL_TRANSCRIPTS', 'table')) WHERE TAG_NAME = 'PERSONAL_DATA'
  UNION ALL SELECT OBJECT_NAME, COLUMN_NAME, TAG_VALUE FROM TABLE(BANKING_HOL.INFORMATION_SCHEMA.TAG_REFERENCES_ALL_COLUMNS('BANKING_HOL.GOVERNANCE.RB_COMPLAINTS', 'table')) WHERE TAG_NAME = 'PERSONAL_DATA'
  UNION ALL SELECT OBJECT_NAME, COLUMN_NAME, TAG_VALUE FROM TABLE(BANKING_HOL.INFORMATION_SCHEMA.TAG_REFERENCES_ALL_COLUMNS('BANKING_HOL.GOVERNANCE.RB_EMAILS', 'table')) WHERE TAG_NAME = 'PERSONAL_DATA'
  UNION ALL SELECT OBJECT_NAME, COLUMN_NAME, TAG_VALUE FROM TABLE(BANKING_HOL.INFORMATION_SCHEMA.TAG_REFERENCES_ALL_COLUMNS('BANKING_HOL.GOVERNANCE.RB_FRAUD_CASES', 'table')) WHERE TAG_NAME = 'PERSONAL_DATA'
  UNION ALL SELECT OBJECT_NAME, COLUMN_NAME, TAG_VALUE FROM TABLE(BANKING_HOL.INFORMATION_SCHEMA.TAG_REFERENCES_ALL_COLUMNS('BANKING_HOL.GOVERNANCE.RB_SAR_NARRATIVES', 'table')) WHERE TAG_NAME = 'PERSONAL_DATA'
),
POLICIES AS (
  SELECT 'RB_CUSTOMERS' AS TABLE_NAME, REF_COLUMN_NAME AS COLUMN_NAME, POLICY_NAME FROM TABLE(BANKING_HOL.INFORMATION_SCHEMA.POLICY_REFERENCES(REF_ENTITY_NAME => 'BANKING_HOL.GOVERNANCE.RB_CUSTOMERS', REF_ENTITY_DOMAIN => 'TABLE')) WHERE POLICY_KIND = 'MASKING_POLICY'
  UNION ALL SELECT 'RB_ACCOUNTS', REF_COLUMN_NAME, POLICY_NAME FROM TABLE(BANKING_HOL.INFORMATION_SCHEMA.POLICY_REFERENCES(REF_ENTITY_NAME => 'BANKING_HOL.GOVERNANCE.RB_ACCOUNTS', REF_ENTITY_DOMAIN => 'TABLE')) WHERE POLICY_KIND = 'MASKING_POLICY'
  UNION ALL SELECT 'RB_TRANSACTIONS', REF_COLUMN_NAME, POLICY_NAME FROM TABLE(BANKING_HOL.INFORMATION_SCHEMA.POLICY_REFERENCES(REF_ENTITY_NAME => 'BANKING_HOL.GOVERNANCE.RB_TRANSACTIONS', REF_ENTITY_DOMAIN => 'TABLE')) WHERE POLICY_KIND = 'MASKING_POLICY'
  UNION ALL SELECT 'RB_CALL_TRANSCRIPTS', REF_COLUMN_NAME, POLICY_NAME FROM TABLE(BANKING_HOL.INFORMATION_SCHEMA.POLICY_REFERENCES(REF_ENTITY_NAME => 'BANKING_HOL.GOVERNANCE.RB_CALL_TRANSCRIPTS', REF_ENTITY_DOMAIN => 'TABLE')) WHERE POLICY_KIND = 'MASKING_POLICY'
  UNION ALL SELECT 'RB_COMPLAINTS', REF_COLUMN_NAME, POLICY_NAME FROM TABLE(BANKING_HOL.INFORMATION_SCHEMA.POLICY_REFERENCES(REF_ENTITY_NAME => 'BANKING_HOL.GOVERNANCE.RB_COMPLAINTS', REF_ENTITY_DOMAIN => 'TABLE')) WHERE POLICY_KIND = 'MASKING_POLICY'
  UNION ALL SELECT 'RB_EMAILS', REF_COLUMN_NAME, POLICY_NAME FROM TABLE(BANKING_HOL.INFORMATION_SCHEMA.POLICY_REFERENCES(REF_ENTITY_NAME => 'BANKING_HOL.GOVERNANCE.RB_EMAILS', REF_ENTITY_DOMAIN => 'TABLE')) WHERE POLICY_KIND = 'MASKING_POLICY'
  UNION ALL SELECT 'RB_FRAUD_CASES', REF_COLUMN_NAME, POLICY_NAME FROM TABLE(BANKING_HOL.INFORMATION_SCHEMA.POLICY_REFERENCES(REF_ENTITY_NAME => 'BANKING_HOL.GOVERNANCE.RB_FRAUD_CASES', REF_ENTITY_DOMAIN => 'TABLE')) WHERE POLICY_KIND = 'MASKING_POLICY'
  UNION ALL SELECT 'RB_SAR_NARRATIVES', REF_COLUMN_NAME, POLICY_NAME FROM TABLE(BANKING_HOL.INFORMATION_SCHEMA.POLICY_REFERENCES(REF_ENTITY_NAME => 'BANKING_HOL.GOVERNANCE.RB_SAR_NARRATIVES', REF_ENTITY_DOMAIN => 'TABLE')) WHERE POLICY_KIND = 'MASKING_POLICY'
)
SELECT T.TABLE_NAME, T.COLUMN_NAME, T.TAG_VALUE, P.POLICY_NAME, IFF(P.POLICY_NAME IS NULL, 'GAP', 'PROTECTED') AS STATUS
FROM TAGGED T LEFT JOIN POLICIES P ON P.TABLE_NAME = T.TABLE_NAME AND P.COLUMN_NAME = T.COLUMN_NAME;

-- 5. A new personal column: tag it and it is protected at once
ALTER TABLE RB_CUSTOMERS MODIFY COLUMN TOTAL_DEBT_GBP SET TAG PERSONAL_DATA = 'FINANCIAL';

-- 6. A protected data product that carries the policies to anyone who reads it
CREATE OR REPLACE VIEW CUSTOMER_PROTECTED AS
SELECT C.CUSTOMER_ID, C.FIRST_NAME, C.LAST_NAME, C.DATE_OF_BIRTH, C.POSTCODE, C.ANNUAL_INCOME_GBP, C.CREDIT_SCORE, A.PRODUCT, A.BALANCE_GBP
FROM RB_CUSTOMERS C JOIN RB_ACCOUNTS A ON A.CUSTOMER_ID = C.CUSTOMER_ID;
GRANT SELECT ON VIEW CUSTOMER_PROTECTED TO ROLE HOL_RESTRICTED;
