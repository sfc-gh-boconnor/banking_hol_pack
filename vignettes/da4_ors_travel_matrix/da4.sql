-- Question: "How far is each neighbourhood from a branch, and from the next one
--            if it closes?", for every neighbourhood at once, from real roads.
-- Prereq:   DA3 recommended. Uses BANKING_HOL.RETAIL.BRANCH_CELL_TRAVEL, the matrix
--           the lab ships (precomputed with OpenRouteService). Nothing to install.
-- Reference SQL for each step in README.md.
